import {test} from 'node:test';
import assert from 'node:assert/strict';
import {createDb,migrate} from '../server/db.js';
import {createRepository} from '../server/repository.js';
import {createAuth,hashPassword} from '../server/auth.js';
import {createApi} from '../server/api.js';
test('authenticated HTTP API validates origin, size, drafts, revisions and error boundaries',async t=>{
 const db=createDb({url:'file::memory:'});t.after(()=>db.close());await migrate(db);
 const auth=createAuth({db,passwordHash:await hashPassword('secret'),authSecret:'test'});
 const handler=createApi({repository:createRepository(db),auth,origin:'http://localhost'});
 let cookie='';const call=(path,method='GET',body,origin='http://localhost')=>handler(new Request(`http://localhost/api/${path}`,{method,headers:{origin,cookie,'content-type':'application/json'},...(body===undefined?{}:{body:typeof body==='string'?body:JSON.stringify(body)})}));
 for(const method of ['GET','POST','PUT','DELETE']) assert.equal((await call('documents/a',method)).status,401);
 const login=await call('auth/login','POST',{password:'secret'});assert.equal(login.status,200);cookie=login.headers.get('set-cookie').split(';')[0];
 assert.equal((await call('auth/session')).status,200);
 assert.equal((await call('documents','POST',{},'http://evil.test')).status,403);
 assert.equal((await call('documents','POST','{')).status,400);
 assert.equal((await call('documents','POST',' '.repeat(1048577))).status,413);
 const draft={name:'',exercises:[],goals:{}};
 let result=await call('documents','POST',{id:'a',kind:'template',document:draft});assert.equal(result.status,201);assert.match(result.headers.get('cache-control'),/no-store/);
 assert.equal((await (await call('documents?kind=template')).json()).records.length,1);
 result=await call('documents/a','PUT',{revision:1,document:{...draft,name:'Changed'}});assert.equal((await result.json()).record.revision,2);
 assert.equal((await call('documents/a','PUT',{revision:1,document:draft})).status,409);
 assert.equal((await call('documents/a','PATCH',{})).status,405);
 assert.equal((await call('documents/a','DELETE',{revision:2})).status,204);
 assert.equal((await call('documents/a')).status,404);
 const cycle={name:'',mode:'simple',goals:{},workouts:[],sequence:[{type:'rest',id:'r'}]};
 assert.equal((await call('documents','POST',{id:'cycle',kind:'program',document:cycle})).status,201);
 assert.deepEqual((await (await call('documents/cycle')).json()).record.document,cycle);
 assert.equal((await call('documents/cycle','PUT',{revision:1,document:{...cycle,sequence:[{type:'workout',workoutId:'missing'}]}})).status,400);
 assert.equal((await (await call('documents/cycle')).json()).record.revision,1);
 await call('auth/logout','POST',{});assert.equal((await call('auth/session')).status,401);
 const alias=createApi({repository:createRepository(db),auth,origin:'https://app.example'});
 const post=(url,origin)=>alias(new Request(url,{method:'POST',headers:{...(origin?{origin}:{}),'content-type':'application/json'},body:JSON.stringify({password:'secret'})}));
 const fromAlias=await post('https://alias.example/api/auth/login','https://alias.example');
 assert.equal(fromAlias.status,200);assert.match(fromAlias.headers.get('set-cookie'),/; Secure/);
 assert.equal((await post('https://alias.example/api/auth/login','https://app.example')).status,200);
 assert.equal((await post('https://alias.example/api/auth/login','https://evil.test')).status,403);
 assert.equal((await post('https://alias.example/api/auth/login')).status,403);
 const local=await post('http://127.0.0.1:3000/api/auth/login','http://127.0.0.1:3000');
 assert.equal(local.status,200);assert.doesNotMatch(local.headers.get('set-cookie'),/Secure/);
 const forwarded=createApi({repository:createRepository(db),auth,origin:'https://app.example',requestOrigin:()=>'https://alias.example'});
 assert.equal((await forwarded(new Request('http://internal/api/auth/login',{method:'POST',headers:{origin:'https://alias.example','content-type':'application/json'},body:JSON.stringify({password:'secret'})}))).status,200);
 const broken=createApi({repository:{list:()=>{throw Error('SQL secret');}},auth:{session:async()=>true},origin:'http://localhost'});
 const failed=await broken(new Request('http://localhost/api/documents?kind=template'));assert.equal(failed.status,503);assert.equal((await failed.text()).includes('SQL'),false);
});
